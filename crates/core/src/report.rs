//! Markdown project reports.
//!
//! A report is the printable artifact of a project: write it to a file, open
//! it in any editor or browser, and print it. Generating it here keeps
//! printing out of the GUI (and any print-dialog dependency) while giving the
//! CLI a headless report command.
//!
//! The report has four sections, omitted when they carry no information:
//!
//! * **Schedule** — every activity with its duration, scheduled dates, total
//!   float, criticality and assigned resources.
//! * **Resources** — per resource: capacity, committed days, over-allocated
//!   days.
//! * **Earned value** — metrics against the most recent baseline at a status
//!   date; only written when a baseline exists.
//! * **Baselines** — name, capture date and snapshot count.
//!
//! [`project_report_pdf`] renders the same report as a print-ready PDF, so a
//! report can be printed without any tool but a browser or a PDF reader. All
//! generated punctuation is ASCII: typographic characters are transliterated
//! on the way out, because the base-14 PDF fonts have no glyphs for them.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use time::Date;

use crate::engine::{evm_metrics, resource_conflicts, resource_histogram, schedule, Schedule};
use crate::model::{Project, ResourceId};
use crate::pdf::{paginate, Pdf, TextLine};

/// Generate a Markdown report for `project` as of `status_date`.
///
/// The project is scheduled first; if scheduling fails the report says so and
/// skips the date-dependent sections rather than emitting an empty document.
#[must_use]
pub fn project_report(project: &Project, status_date: Date) -> String {
    let mut report = String::new();
    let _ = writeln!(report, "# {}", project.name);
    let _ = writeln!(report);
    let _ = writeln!(report, "Status date: {status_date}");
    let _ = writeln!(
        report,
        "Generated by Cadence — {} activities, {} resources, {} baseline(s)",
        project.activities.len(),
        project.resources.len(),
        project.baselines.len()
    );

    let computed = match schedule(project) {
        Ok(schedule) => Some(schedule),
        Err(error) => {
            let _ = writeln!(report);
            let _ = writeln!(report, "> The project cannot be scheduled: {error}");
            None
        }
    };

    if let Some(computed) = &computed {
        schedule_section(project, computed, &mut report);
        resources_section(project, computed, &mut report);
    }
    earned_value_section(project, status_date, &mut report);
    baselines_section(project, &mut report);

    // One ASCII pass before anything consumes the text: the base-14 PDF
    // fonts have no glyphs for typographic punctuation, and the Markdown
    // reads the same for it.
    transliterate(&report)
}

/// Render the report as a print-ready PDF.
///
/// The Markdown is the source: headings become bold text at heading sizes,
/// quoted lines become body text, and everything else keeps the body size.
/// Long lines wrap and the result paginates over as many A4 pages as it needs,
/// so a hundred-activity project prints as a hundred-activity document instead
/// of one very tall page.
#[must_use]
pub fn project_report_pdf(project: &Project, status_date: Date) -> Vec<u8> {
    let markdown = project_report(project, status_date);
    let mut pdf = Pdf::new();
    for page in paginate(&pdf_lines(&markdown)) {
        pdf.text_page(page);
    }
    pdf.to_bytes()
}

/// Turn report Markdown into PDF text lines, keeping its structure.
fn pdf_lines(markdown: &str) -> Vec<TextLine> {
    let mut lines = Vec::new();
    for raw in markdown.lines() {
        let trimmed = raw.trim();
        if trimmed.is_empty() {
            continue;
        }
        if let Some(title) = trimmed.strip_prefix("# ") {
            lines.push(TextLine::heading(title, 18.0));
        } else if let Some(heading) = trimmed.strip_prefix("## ") {
            lines.push(TextLine::heading(heading, 13.0));
        } else if let Some(quoted) = trimmed.strip_prefix('>') {
            lines.push(TextLine::body(quoted.trim()));
        } else {
            lines.push(TextLine::body(trimmed));
        }
    }
    lines
}

fn schedule_section(project: &Project, computed: &Schedule, report: &mut String) {
    let _ = writeln!(report);
    let _ = writeln!(
        report,
        "## Schedule ({})",
        date_range(computed.project_start, computed.project_finish)
    );
    let _ = writeln!(report);
    let _ = writeln!(
        report,
        "| ID | Activity | Days | Start | Finish | Float | Critical | Resources |"
    );
    let _ = writeln!(report, "|---|---|---:|---|---|---:|---|---|");

    for activity in &project.activities {
        let Some(result) = computed.activity(activity.id) else {
            continue;
        };
        let resources = activity
            .resources
            .iter()
            .filter_map(|id| project.resource(*id))
            .map(|resource| resource.name.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            report,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            activity.id,
            escape_table(&activity.name),
            activity.original_duration,
            result.scheduled_start,
            result.scheduled_finish,
            result.total_float,
            if result.critical { "yes" } else { "" },
            escape_table(&resources),
        );
    }
}

fn resources_section(project: &Project, computed: &Schedule, report: &mut String) {
    let histogram = resource_histogram(project, computed);
    let conflicts = resource_conflicts(project, computed);

    let mut committed: BTreeMap<ResourceId, usize> = BTreeMap::new();
    for assignments in histogram.entries.values() {
        for assignment in assignments {
            *committed.entry(assignment.resource_id).or_default() += 1;
        }
    }

    let _ = writeln!(report);
    let _ = writeln!(report, "## Resources");
    let _ = writeln!(report);
    let _ = writeln!(
        report,
        "| Resource | Kind | Capacity | Committed days | Over-allocated days |"
    );
    let _ = writeln!(report, "|---|---|---:|---:|---:|");

    for resource in &project.resources {
        let over = conflicts
            .iter()
            .filter(|conflict| conflict.resource_id == resource.id)
            .count();
        let _ = writeln!(
            report,
            "| {} | {:?} | {} | {} | {} |",
            escape_table(&resource.name),
            resource.kind,
            resource.capacity,
            committed.get(&resource.id).copied().unwrap_or(0),
            over,
        );
    }
}

fn earned_value_section(project: &Project, status_date: Date, report: &mut String) {
    let Some(baseline) = project.baselines.iter().max_by_key(|baseline| baseline.id) else {
        return;
    };
    let metrics = evm_metrics(project, Some(baseline), status_date);

    let _ = writeln!(report);
    let _ = writeln!(
        report,
        "## Earned value (baseline \"{}\", status date {status_date})",
        baseline.name
    );
    let _ = writeln!(report);
    let _ = writeln!(report, "| Metric | Value |");
    let _ = writeln!(report, "|---|---:|");
    let _ = writeln!(
        report,
        "| Budget at completion | {} |",
        money(metrics.budget_at_completion)
    );
    let _ = writeln!(
        report,
        "| Planned value | {} |",
        money(metrics.planned_value)
    );
    let _ = writeln!(report, "| Earned value | {} |", money(metrics.earned_value));
    let _ = writeln!(report, "| Actual cost | {} |", money(metrics.actual_cost));
    let _ = writeln!(
        report,
        "| Schedule variance | {} |",
        money(metrics.schedule_variance)
    );
    let _ = writeln!(
        report,
        "| Cost variance | {} |",
        money(metrics.cost_variance)
    );
    let _ = writeln!(
        report,
        "| Schedule performance index | {} |",
        index(metrics.schedule_performance_index)
    );
    let _ = writeln!(
        report,
        "| Cost performance index | {} |",
        index(metrics.cost_performance_index)
    );
}

fn baselines_section(project: &Project, report: &mut String) {
    if project.baselines.is_empty() {
        return;
    }
    let _ = writeln!(report);
    let _ = writeln!(report, "## Baselines");
    let _ = writeln!(report);
    let _ = writeln!(report, "| Baseline | Captured | Snapshots |");
    let _ = writeln!(report, "|---|---|---:|");
    for baseline in &project.baselines {
        let _ = writeln!(
            report,
            "| {} | {} | {} |",
            escape_table(&baseline.name),
            baseline.created_at,
            baseline.snapshots.len()
        );
    }
}

fn date_range(start: Date, finish: Date) -> String {
    format!("{start} to {finish}")
}

fn money(minor_units: i64) -> String {
    format!("{:.2}", minor_units as f64 / 100.0)
}

fn index(value: Option<f64>) -> String {
    value
        .map(|value| format!("{value:.3}"))
        .unwrap_or_else(|| "n/a".to_string())
}

/// Prevent cell text with pipes or line breaks from breaking the table.
fn escape_table(value: &str) -> String {
    value.replace('|', "\\|").replace(['\n', '\r'], " ")
}

/// Map typographic punctuation onto ASCII equivalents.
///
/// The base-14 PDF fonts carry no glyphs for characters like the em dash, so
/// such punctuation would print as mojibake; one pass over the finished
/// Markdown keeps both it and the PDF rendered from it legible.
fn transliterate(text: &str) -> String {
    text.replace('\u{2014}', "--") // em dash
        .replace('\u{2013}', "-") // en dash
        .replace('\u{2018}', "'") // left single quotation mark
        .replace('\u{2019}', "'") // right single quotation mark
        .replace('\u{201C}', "\"") // left double quotation mark
        .replace('\u{201D}', "\"") // right double quotation mark
        .replace('\u{2026}', "...") // horizontal ellipsis
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::capture_baseline;
    use crate::model::{
        Activity, ActivityBaselineSnapshot, ActivityId, Baseline, BaselineId, Constraint, LinkType,
        Relationship, RelationshipId, Resource, ResourceId,
    };
    use time::Month;

    fn date(year: i32, month: Month, day: u8) -> Date {
        Date::from_calendar_date(year, month, day).expect("valid date")
    }

    fn sample() -> Project {
        let start = date(2026, Month::January, 5);
        let mut project = Project::new("Bridge & Road", start);

        let mut survey = Activity::new(ActivityId(1), "Survey | works", 2);
        survey.percent_complete = Some(5000);
        survey.budget_at_completion = Some(150_000);
        project.activities.push(survey);

        let mut excavate = Activity::new(ActivityId(2), "Excavate", 3);
        excavate.constraint = Constraint::StartNoEarlierThan(date(2026, Month::January, 8));
        project.activities.push(excavate);

        // Independent of the chain, so it overlaps the survey for one crew.
        project
            .activities
            .push(Activity::new(ActivityId(3), "Pour", 2));

        project.relationships.push(Relationship::new(
            RelationshipId(1),
            ActivityId(1),
            ActivityId(2),
            LinkType::Fs,
            0,
        ));

        project
            .resources
            .push(Resource::new(ResourceId(1), "Crew A"));
        project.activities[0].resources = vec![ResourceId(1)];
        project.activities[1].resources = vec![ResourceId(1)];
        project.activities[2].resources = vec![ResourceId(1)];

        project
    }

    #[test]
    fn the_report_contains_the_schedule_table() {
        let project = sample();
        let report = project_report(&project, date(2026, Month::January, 9));

        assert!(report.starts_with("# Bridge & Road"));
        assert!(report.contains("## Schedule (2026-01-05 to 2026-01-12)"));
        // The survey has one day of float: the excavate cannot start before
        // 2026-01-08, leaving 2026-01-07 free — so it is not critical.
        assert!(report
            .contains("| 1 | Survey \\| works | 2 | 2026-01-05 | 2026-01-06 | 1 |  | Crew A |"));
        assert!(
            report.contains("| 2 | Excavate | 3 | 2026-01-08 | 2026-01-12 | 0 | yes | Crew A |")
        );
        // The pour is independent of the critical chain, so it has float and
        // is not critical.
        assert!(report.contains("| 3 | Pour | 2 | 2026-01-05 | 2026-01-06 | 4 |  | Crew A |"));
    }

    #[test]
    fn resources_appear_with_their_committed_days() {
        let project = sample();
        let report = project_report(&project, date(2026, Month::January, 9));

        assert!(report.contains("## Resources"));
        // The survey and the pour run in parallel on one crew: five committed
        // days across three activities, two of them over capacity.
        assert!(report.contains("| Crew A | Labour | 1 | 7 | 2 |"));
    }

    #[test]
    fn earned_value_appears_only_with_a_baseline() {
        let mut project = sample();
        assert!(!project_report(&project, date(2026, Month::January, 9)).contains("Earned value"));

        let computed = schedule(&project).expect("schedule");
        let baseline = capture_baseline(
            &project,
            &computed,
            BaselineId(1),
            "Baseline 1",
            date(2026, Month::January, 5),
        );
        project.baselines.push(baseline);

        let report = project_report(&project, date(2026, Month::January, 9));
        assert!(report.contains("## Earned value"));
        assert!(report.contains("| Budget at completion | 1500.00 |"));
        assert!(report.contains("## Baselines"));
        assert!(report.contains("| Baseline 1 | 2026-01-05 | 3 |"));
    }

    #[test]
    fn the_most_recent_baseline_drives_earned_value() {
        let mut project = sample();
        project.baselines.push(Baseline {
            id: BaselineId(1),
            name: "First draft".to_string(),
            created_at: date(2026, Month::January, 5),
            snapshots: Vec::new(),
        });
        project.baselines.push(Baseline {
            id: BaselineId(2),
            name: "Board-approved".to_string(),
            created_at: date(2026, Month::January, 6),
            snapshots: vec![ActivityBaselineSnapshot {
                activity_id: ActivityId(1),
                baseline_duration: 2,
                baseline_start: Some(date(2026, Month::January, 5)),
                baseline_finish: Some(date(2026, Month::January, 6)),
            }],
        });

        let report = project_report(&project, date(2026, Month::January, 9));
        assert!(report.contains("baseline \"Board-approved\""));
        assert!(!report.contains("baseline \"First draft\""));
        assert!(report.contains("| Board-approved | 2026-01-06 | 1 |"));
    }

    #[test]
    fn an_unschedulable_project_reports_the_problem() {
        let start = date(2026, Month::January, 5);
        let mut project = Project::new("Cyclic", start);
        project
            .activities
            .push(Activity::new(ActivityId(1), "A", 1));
        project
            .activities
            .push(Activity::new(ActivityId(2), "B", 1));
        project.relationships.push(Relationship::new(
            RelationshipId(1),
            ActivityId(1),
            ActivityId(2),
            LinkType::Fs,
            0,
        ));
        project.relationships.push(Relationship::new(
            RelationshipId(2),
            ActivityId(2),
            ActivityId(1),
            LinkType::Fs,
            0,
        ));

        let report = project_report(&project, start);
        assert!(report.contains("cannot be scheduled"));
        assert!(!report.contains("## Schedule"));
    }

    #[test]
    fn table_cells_survive_pipes_and_line_breaks() {
        assert_eq!(escape_table("a|b"), "a\\|b");
        assert_eq!(escape_table("a\nb"), "a b");
    }

    #[test]
    fn typographic_punctuation_is_transliterated_to_ascii() {
        assert_eq!(transliterate("a \u{2014} b"), "a -- b");
        assert_eq!(transliterate("f \u{2013} g"), "f - g");
        assert_eq!(transliterate("\u{2018}c\u{2019}"), "'c'");
        assert_eq!(transliterate("\u{201C}d\u{201D}"), "\"d\"");
        assert_eq!(transliterate("e\u{2026}"), "e...");
        // Plain ASCII passes through untouched.
        assert_eq!(transliterate("plain text"), "plain text");
    }

    #[test]
    fn an_em_dash_in_the_report_becomes_ascii() {
        let start = date(2026, Month::January, 5);
        let mut project = Project::new("Bridge \u{2014} west span", start);
        project
            .activities
            .push(Activity::new(ActivityId(1), "Survey", 2));

        let report = project_report(&project, start);

        assert!(report.starts_with("# Bridge -- west span"));
        assert!(report.contains("Generated by Cadence --"));
        assert!(!report.contains('\u{2014}'));
    }
}
